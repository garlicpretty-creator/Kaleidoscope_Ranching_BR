// Writes data/burntTeaCatalog.js: what this pack tells burnt-tea-dev's packs (Order To Cook, Grilling) about itself.
// Read from the pack's own item and recipe JSON and its zh_TW.lang, so the table cannot drift from the pack.
//   node tools/gen_burnt_tea.mjs <BP dir> <RP dir> <namespace> <out file> [--check]
// --check: exit 1 if <out file> is not what this would write (tests run it).
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const [bp, rp, ns, out, flag] = process.argv.slice(2);
if (!bp || !rp || !ns || !out) { console.error("usage: gen_burnt_tea.mjs <BP> <RP> <namespace> <out> [--check]"); process.exit(2); }

const walk = (dir) => (existsSync(dir) ? readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? walk(join(dir, f)) : [join(dir, f)])) : []);
const json = (file) => { try { return JSON.parse(readFileSync(file, "utf8").replace(/^\uFEFF/, "").replace(/^\s*\/\/.*$/gm, "")); } catch { return null; } };

const lang = new Map();
for (const line of readFileSync(join(rp, "texts", "zh_TW.lang"), "utf8").split(/\r?\n/)) {
  const eq = line.indexOf("=");
  if (eq > 0 && !line.startsWith("#")) lang.set(line.slice(0, eq).trim(), line.slice(eq + 1).split("\\n")[0].split("\t")[0].replace(/§./g, "").trim());
}

const items = new Map();
for (const file of walk(join(bp, "items")).filter((f) => f.endsWith(".json"))) {
  const item = json(file)?.["minecraft:item"];
  const id = item?.description?.identifier;
  if (!id?.startsWith(`${ns}:`)) continue;
  const c = item.components ?? {};
  const key = String(c["minecraft:display_name"]?.value ?? `item.${id}.name`).replace(/^%/, "");
  const group = String(item.description?.menu_category?.group ?? "");
  items.set(id, { food: c["minecraft:food"], group, // a soup drunk from a bowl is a dish; a drink comes in a cup, glass or bottle
    drink: c["minecraft:use_animation"] === "drink" && c["minecraft:food"]?.using_converts_to !== "minecraft:bowl", label: lang.get(key) ?? lang.get(`item.${id}.name`) });
}

const smoker = [];
for (const file of walk(join(bp, "recipes")).filter((f) => f.endsWith(".json"))) {
  const r = json(file)?.["minecraft:recipe_furnace"];
  if (!r || !(r.tags ?? []).includes("smoker")) continue;
  const input = typeof r.input === "string" ? r.input : r.input?.item;
  const output = typeof r.output === "string" ? r.output : r.output?.item;
  // Only food made from our own ingredient: Grilling cooks skewer ingredients, OTC's stove cooks dishes.
  if (input?.startsWith(`${ns}:`) && items.get(output)?.food) smoker.push([input, output]);
}
smoker.sort((a, b) => a[0].localeCompare(b[0]));
const raw = new Set(smoker.map(([input]) => input));

const foods = [];
for (const [id, it] of [...items].sort((a, b) => a[0].localeCompare(b[0]))) {
  if (!it.food || raw.has(id) || !it.label) continue;          // raw ingredients that a smoker cooks are not menu dishes
  const nutrition = Math.max(0, Math.floor(Number(it.food.nutrition) || 0));
  // A menu dish, not an ingredient: a drink needs 1 hunger (dregs and the like stay out), food 3 or more, so raw
  // vegetables, minces and offal stay out; nothing whose name says it is raw (生…).
  if (nutrition < 1 || (!it.drink && nutrition < 3) || it.label.startsWith("生")) continue;
  if (/\.(catches|ingredients|harvest_crops)$/.test(it.group)) continue;  // creative groups for raw catches and ingredients
  foods.push([id, nutrition, it.label.slice(0, 100), it.drink ? 1 : 0]);
}

const text = `// Generated by tools/gen_burnt_tea.mjs from this pack's items, smoker recipes and zh_TW.lang. Do not edit by hand.
// Plain data: no @minecraft imports.

/** Menu dishes for Order To Cook: [item, nutrition, zh_TW label, 1 if a drink]. */
export const OTC_FOODS = ${JSON.stringify(foods).replace(/\],\[/g, "],\n  [").replace(/^\[\[/, "[\n  [").replace(/\]\]$/, "],\n]")};

/** Smoker recipes, raw ingredient -> cooked food: [input, output]. */
export const SMOKER_RECIPES = ${JSON.stringify(smoker).replace(/\],\[/g, "],\n  [").replace(/^\[\[/, "[\n  [").replace(/\]\]$/, "],\n]")};
`;
if (flag === "--check") {
  const now = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (now !== text) { console.error(`${out} is stale: run tools/gen_burnt_tea.mjs`); process.exit(1); }
  console.log(`${out}: up to date (${foods.length} dishes, ${smoker.length} smoker recipes)`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}: ${foods.length} dishes, ${smoker.length} smoker recipes`);
}
